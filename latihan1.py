nama = "Fajar"
umur = 19
berat = 54.5
terdaftar = True

print("=== 1. Menampilkan Nilai Variabel ===")
print("Nama:", nama)
print("Umur:", umur)
print("Berat:", berat)
print("Terdaftar:", terdaftar)

print("\n=== 2. Menampilkan Tipe Data Setiap Variabel ===")
print("Tipe data nama:", type(nama))
print("Tipe data umur:", type(umur))
print("Tipe data berat:", type(berat))
print("Tipe data terdaftar:", type(terdaftar))

print("\n=== 3. Mengubah Nilai Umur Menjadi 20 ===")
umur = 20
print("Umur setelah diubah:", umur)
print("Tipe data umur setelah diubah:", type(umur))